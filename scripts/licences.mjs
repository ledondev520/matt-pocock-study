import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'

/**
 * MIT sources whose material this site reuses. Each LICENSE file under third_party/ is a
 * byte-for-byte copy of the upstream repository's LICENSE; the pinned sha256 makes any edit
 * (including a changed copyright holder or year) fail the build.
 */
export const licences = {
  'mattpocock-skills': {
    name: 'mattpocock/skills',
    short: 'mattpocock/skills',
    repo: 'https://github.com/mattpocock/skills',
    file: 'third_party/mattpocock-skills/LICENSE',
    sha256: '0e7ac423bf2c6e223b7c5b156f8cf72da49d748e56a1641402c31f22ad07dbb5',
  },
  archify: {
    name: 'Archify (tt-a1i/archify)',
    short: 'Archify',
    repo: 'https://github.com/tt-a1i/archify',
    file: 'third_party/archify/LICENSE',
    sha256: 'b799ab081703e7821ae5096d2c1abdf14bbdc75e8ea1c4045998c36ed6db9706',
  },
}

/** `read` exists so tests can feed altered bytes through the real hash check. */
export function licenceText(id, read = file => readFileSync(file, 'utf8')) {
  if (!Object.hasOwn(licences, id)) throw new Error(`Unknown licence id: ${id}`)
  const entry = licences[id]
  const text = read(entry.file)
  if (createHash('sha256').update(text).digest('hex') !== entry.sha256) throw new Error(`Licence text changed: ${entry.file}`)
  return text
}

const escape = value => value.replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c])

/**
 * The licence block as page HTML and as exported Markdown. On the page the full text sits in a
 * native <details>, closed by default: a one-line summary names the source, and the verbatim text
 * opens on click, Enter or Space. The .md export keeps the heading and the text in the open.
 */
export function licenceBlock(id, lang) {
  const text = licenceText(id)
  const label = `${lang === 'zh' ? '完整许可：' : 'Full licence: '}${licences[id].name}`
  const summary = lang === 'zh' ? `完整许可：${licences[id].short}（MIT）` : `Full licence: ${licences[id].short} (MIT)`
  return {
    html: `<details class="licence-text"><summary>${escape(summary)}</summary><pre lang="en">${escape(text)}</pre></details>`,
    markdown: `### ${label}\n\n\`\`\`text\n${text.trimEnd()}\n\`\`\``,
  }
}

/** True when markup contains an inline SVG generated by the Archify pipeline (root class arch-*). */
export const embedsArchify = markup => /<svg\b[^>]*\sclass="(?:[^"]*\s)?arch-[A-Za-z0-9-]+/.test(markup)

/**
 * The one comment a diagram SVG file may carry: Archify's full licence, generated from the
 * hash-checked text, as the first bytes of the file. Its exact bytes are fixed here.
 */
export function archifySvgComment() {
  const text = licenceText('archify')
  if (text.includes('--')) throw new Error('Licence text cannot sit inside an XML comment')
  // No URL: diagram files must not contain any http(s) reference beyond the SVG namespace.
  return `<!--\nCSS in this file is adapted from ${licences.archify.name}, MIT licence:\n\n${text}-->\n`
}

/** Archify page appendix: a short note plus the full licence (HTML and Markdown). */
export function archifyAppendix(lang) {
  const block = licenceBlock('archify', lang)
  const note = lang === 'zh'
    ? `本页说明图内嵌的 CSS 片段改编自 Archify（${licences.archify.repo}），MIT 许可，完整许可如下。`
    : `The diagram CSS on this page is adapted from Archify (${licences.archify.repo}) under the MIT licence; the complete licence follows.`
  return {
    html: `<aside class="licence-appendix"><p>${escape(note)}</p>${block.html}</aside>`,
    markdown: `${note}\n\n${block.markdown}`,
  }
}
